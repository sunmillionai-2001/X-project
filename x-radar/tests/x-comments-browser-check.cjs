const { createRequire } = require('node:module');
const { spawn } = require('node:child_process');
const { pathToFileURL } = require('node:url');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict');
const bundled = createRequire(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/package.json'));
const { chromium } = bundled('playwright');
const base = 'http://127.0.0.1:18904';
const data = fs.mkdtempSync(path.join(os.tmpdir(), 'x-comments-browser-'));
const qa = path.resolve(__dirname, '../../research/qa-x-comments'); fs.mkdirSync(qa, { recursive: true });
const pause = ms => new Promise(r => setTimeout(r, ms));
let child, browser;
(async () => {
  child = spawn(process.execPath, ['--import', pathToFileURL(path.join(__dirname, 'mock-network.mjs')).href, path.join(__dirname, '../server.mjs')], { env: { ...process.env, XRADAR_DATA: data, XRADAR_PORT: '18904', XRADAR_PUBLIC_PROXY: 'off' }, windowsHide: true, stdio: 'pipe' });
  let ready = false;
  for (let n = 0; n < 50; n++) { try { if ((await fetch(base + '/api/health')).ok) { ready = true; break; } } catch {} await pause(150); }
  assert(ready);
  browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/#x');
  await page.locator('.x-card').first().waitFor();
  await page.locator('.progressbox').waitFor({ state: 'hidden' });
  await page.locator('#x-filter-account').selectOption('AI_Jasonyu');
  await page.locator('.x-card [data-action="x-open-comments"]').first().click();
  assert.equal(await page.locator('#x-reader .x-reader-body').count(), 0);
  assert.equal(await page.locator('#x-reader [data-value="comments"]').getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: '补全公开评论', exact: true }).click();
  await page.locator('#x-reader .progressbox').waitFor();
  await page.locator('#x-reader .progressbox').waitFor({ state: 'hidden' });
  await page.locator('.x-comment').nth(2).waitFor();
  assert.equal(await page.locator('.x-comment').count(), 3);
  assert((await page.locator('#x-comments').innerText()).includes('已保存 3 条'));
  assert((await page.locator('#x-comments').innerText()).includes('回复另一条评论'));
  await page.locator('#x-reader [data-value="post"]').click();
  assert.equal(await page.locator('#x-reader .x-reader-body').count(), 1);
  await page.locator('#x-reader [data-value="comments"]').click();
  const commentURL = page.url(); assert(commentURL.includes('/comments'));
  await page.getByRole('button', { name: '高赞优先', exact: true }).click();
  await page.locator('#x-comments').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(qa, 'comments-desktop.png') });
  await page.reload();
  await page.locator('.x-comment').nth(2).waitFor();
  assert.equal(await page.locator('#x-reader .x-reader-body').count(), 0);
  assert.equal(await page.locator('#x-reader [data-value="comments"]').getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.locator('.x-comments-hub').getByRole('button', { name: '查看 3 条评论', exact: true }).click();
  await page.locator('.x-comment').nth(2).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#x-comments').scrollIntoViewIfNeeded();
  assert.equal(await page.locator('#x-reader').evaluate(el => el.scrollWidth > el.clientWidth), false);
  assert.equal(await page.locator('#x-reader').evaluate(el => el.getBoundingClientRect().width <= innerWidth), true);
  await page.screenshot({ path: path.join(qa, 'comments-mobile.png') });
  assert.deepEqual(errors, []);
  console.log('Comments browser acceptance passed: card entry, top tabs, saved-comment hub, deep link, collection, sorting, persistence, desktop and mobile.');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { await browser?.close(); if (child?.exitCode === null) child.kill(); });
