test('manual illustration import needs no image key, preserves approvals, replaces assets and survives restart', { timeout: 30000 }, async t => {
  await start(); t.after(stop);
  await request('/api/settings', { imageMode: 'manual', clearImageKey: true });
  await assert.rejects(() => request('/api/settings', { imageMode: 'invalid' }), /请选择/);
  const initial = await request('/api/state');
  assert.equal(initial.settings.hasImageKey, false);
  let p = await request('/api/project', { cardId: initial.daily.cards[0].id });
  const pd = extra => ({ id: p.id, revision: p.revision, ...extra });
  p = await request('/api/outline', pd({ angle: p.angle, outline: p.outline }));
  p = await request('/api/test', pd({ notes: '这是一份合成测试记录，明确区分实际截图和生成示意图，不用于真实发布。' }));
  p = await request('/api/draft/save', pd({ body: '手动导入流程测试稿。'.repeat(90) }));
  p = await request('/api/draft/approve', pd());
  p = await request('/api/plan/save', pd({ images: [{ kind: 'illustration', title: '网页生成的示意插图', description: '合成导入测试', prompt: '一个清楚的示意画面', points: [] }] }));
  const planId = p.plan[0].id;
  const pixel = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aNAAAAABJRU5ErkJggg==';
  await assert.rejects(() => request('/api/upload', pd({ planId, data: pixel })), /确认/);
  p = await request('/api/plan/approve', pd());
  const callsBefore = (await request('/api/state')).calls.length;
  await assert.rejects(() => job('/api/image', pd({ planId })), /网页生成后导入/);
  assert.equal((await request('/api/state')).calls.length, callsBefore);
  await assert.rejects(() => request('/api/upload', pd({ planId, data: 'invalid' })), /PNG/);
  p = await request('/api/upload', pd({ planId, label: 'ChatGPT 示例.png', data: pixel }));
  assert.equal(p.assets[0].kind, 'illustration'); assert.equal(p.assets[0].origin, 'import');
  assert.equal(p.draftApproved, true); assert.equal(p.planApproved, true); assert.equal(p.testApproved, true);
  const oldFile = p.assets[0].file;
  p = await request('/api/upload', pd({ planId, label: '替换后的插图.png', data: pixel }));
  assert.equal(p.assets.filter(a => a.planId === planId).length, 1); assert.notEqual(p.assets[0].file, oldFile);
  p = await request('/api/complete', pd()); assert.equal(p.stage, 'done');
  await stop(); await start();
  const restored = (await request('/api/state')).projects.find(r => r.id === p.id);
  assert.equal(restored.stage, 'done'); assert.equal(restored.assets[0].kind, 'illustration');
  const image = await fetch(base + '/assets/' + restored.assets[0].file); assert.equal(image.status, 200);
});

test('image connection test persists a separate preview, diagnoses group permissions and never exposes provider credentials', { timeout: 30000 }, async t => {
  await start(); t.after(stop);
  const originalProjects = (await request('/api/state')).projects;
  await request('/api/settings', { imageMode: 'api', imageBase: 'https://example.com/v1', imageModel: 'fixture-image', imageKey: 'secret-image-test-only' });
  const result = await job('/api/image/test', {});
  assert.equal(result.ok, true);
  let state = await request('/api/state');
  assert.equal(state.settings.imageCheck.status, 'ready');
  assert.equal(state.settings.imageCheck.previewFile, result.file);
  assert.deepEqual(state.projects, originalProjects, 'Testing image credentials must not approve or alter drafts');
  const preview = await fetch(base + '/assets/' + result.file);
  assert.equal(preview.headers.get('content-type'), 'image/png'); assert((await preview.arrayBuffer()).byteLength > 0);
  await stop(); await start();
  assert.equal((await request('/api/state')).settings.imageCheck.previewFile, result.file);
  await request('/api/settings', { imagePrice: '' });
  assert.equal((await request('/api/state')).settings.imageCheck.status, 'ready');
  await request('/api/settings', { imageModel: 'blocked-image' });
  assert.equal((await request('/api/state')).settings.imageCheck, null);
  await assert.rejects(() => job('/api/image/test', {}), /当前密钥所属分组未开启图片生成/);
  state = await request('/api/state');
  assert.equal(state.settings.imageCheck.status, 'failed');
  assert.equal(state.settings.imageCheck.code, 'image_group_disabled');
  assert.equal(state.settings.imageCheck.previewFile, undefined);
  assert(state.calls.some(c => c.purpose === '图片连接测试' && c.status === 'failed_or_invalid'));
  assert(!JSON.stringify(state).includes('secret-image-test-only'));
  await request('/api/settings', { imageModel: 'invalid-error-image' });
  await assert.rejects(() => job('/api/image/test', {}), /图片服务返回 400/);
  assert(!JSON.stringify(await request('/api/state')).includes('private provider error'));
  await request('/api/settings', { imageKey: 'replacement-image-test-only' });
  assert.equal((await request('/api/state')).settings.imageCheck, null);
});
