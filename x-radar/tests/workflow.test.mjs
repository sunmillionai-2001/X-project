import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const data = fs.mkdtempSync(path.join(os.tmpdir(), 'x-radar-acceptance-'));
const port = 18770; const base = `http://127.0.0.1:${port}`;
let child;
const pause = ms => new Promise(r => setTimeout(r, ms));
async function start() { let log = ''; child = spawn(process.execPath, ['--import', pathToFileURL(path.join(here, 'mock-network.mjs')).href, path.join(here, '../server.mjs')], { env: { ...process.env, XRADAR_DATA: data, XRADAR_PORT: String(port), XRADAR_PUBLIC_PROXY: 'off' }, stdio: 'pipe', windowsHide: true }); child.stderr.on('data', c => { log += c.toString(); }); for (let i = 0; i < 60; i++) { try { if ((await fetch(base + '/api/health')).ok) return; } catch {} await pause(200); } throw Error('test server failed: ' + log); }
async function stop() { if (child && child.exitCode === null) { child.kill(); await new Promise(r => child.once('exit', r)); } }
async function request(route, d) { const r = await fetch(base + route, d === undefined ? {} : { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: base }, body: JSON.stringify(d) }); const out = await r.json(); if (!r.ok) throw Error(out.error); return out; }
async function job(route, d) { let j = await request(route, d); for (let i = 0; i < 300 && j.status === 'running'; i++) { await pause(60); j = await request('/api/job/' + j.id); } if (j.status === 'error') throw Error(j.error); assert.equal(j.status, 'done'); return j.result; }
